export const getStageById        = (id)        => STORY_STAGES.find((s) => s.id === id);
export const getStagesForChapter = (chapterId) => STORY_STAGES.filter((s) => s.chapterId === chapterId);
export const getChapterById      = (id)        => CHAPTER_DEFS.find((c) => c.id === id);

export const isStageUnlocked = (stageId, completedStages) => {
  if (stageId === STAGE_ORDER[0]) return true;
  const idx = STAGE_ORDER.indexOf(stageId);
  if (idx < 0) return false;
  return completedStages.includes(STAGE_ORDER[idx - 1]);
};

